#!/usr/bin/env python3
"""Regenerate core/src/fontdata.rs from the vendored Adobe AFM files.

    python3 tools/gen_fontdata.py           # rewrite core/src/fontdata.rs
    python3 tools/gen_fontdata.py --check   # exit 1, with a diff, if it is out of date

Reads only core/afm/*.afm, so it needs no network and only the Python 3
standard library. For each font it emits the advance width of every WinAnsi
code in 32..=126 and 160..=255 (0 everywhere else), looked up by Adobe glyph
name, plus the descriptor metrics from the AFM header (FontBBox, Ascender,
Descender, CapHeight, ItalicAngle, StdVW).
"""

import argparse
import difflib
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AFM_DIR = ROOT / "core" / "afm"
OUT = ROOT / "core" / "src" / "fontdata.rs"

# Emitted as `pub static <NAME>: Metrics`; `Font::metrics` in core/src/lib.rs
# refers to these by name.
FONTS = ["Helvetica", "Helvetica-Bold", "Courier", "Courier-Bold"]

HEADER = """\
// @generated by tools/gen_fontdata.py from core/afm/*.afm. Do not edit; rerun the script.
// Glyph widths and descriptor metrics: Copyright (c) 1985, 1987, 1989, 1990, 1997 Adobe Systems
// Incorporated. All Rights Reserved. Source AFM files and their licence: core/afm/ (see core/afm/LICENSE).

pub struct Metrics {
    /// Width per WinAnsi code 0..=255, 1/1000 em; 0 = code not supported.
    pub widths: [u16; 256],
    pub bbox: [i32; 4],
    pub ascent: i32,
    pub descent: i32,
    pub cap_height: i32,
    pub italic_angle: i32,
    pub stem_v: i32,
}
"""

# WinAnsiEncoding glyph names (ISO 32000 Annex D), ASCII range.
PUNCTUATION = {
    32: "space", 33: "exclam", 34: "quotedbl", 35: "numbersign", 36: "dollar",
    37: "percent", 38: "ampersand", 39: "quotesingle", 40: "parenleft",
    41: "parenright", 42: "asterisk", 43: "plus", 44: "comma", 45: "hyphen",
    46: "period", 47: "slash", 58: "colon", 59: "semicolon", 60: "less",
    61: "equal", 62: "greater", 63: "question", 64: "at", 91: "bracketleft",
    92: "backslash", 93: "bracketright", 94: "asciicircum", 95: "underscore",
    96: "grave", 123: "braceleft", 124: "bar", 125: "braceright", 126: "asciitilde",
}
DIGITS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]

# Latin-1 codes whose glyph names cannot be derived from the Unicode name.
LATIN1_SYMBOLS = {
    160: "space", 161: "exclamdown", 162: "cent", 163: "sterling", 164: "currency",
    165: "yen", 166: "brokenbar", 167: "section", 168: "dieresis", 169: "copyright",
    170: "ordfeminine", 171: "guillemotleft", 172: "logicalnot", 173: "hyphen",
    174: "registered", 175: "macron", 176: "degree", 177: "plusminus",
    178: "twosuperior", 179: "threesuperior", 180: "acute", 181: "mu",
    182: "paragraph", 183: "periodcentered", 184: "cedilla", 185: "onesuperior",
    186: "ordmasculine", 187: "guillemotright", 188: "onequarter", 189: "onehalf",
    190: "threequarters", 191: "questiondown", 215: "multiply", 223: "germandbls",
    247: "divide",
}
ACCENTS = {
    "GRAVE": "grave", "ACUTE": "acute", "CIRCUMFLEX": "circumflex", "TILDE": "tilde",
    "DIAERESIS": "dieresis", "RING ABOVE": "ring", "CEDILLA": "cedilla",
}
LIGATURE_LETTERS = {"AE": ("AE", "ae"), "ETH": ("Eth", "eth"), "THORN": ("Thorn", "thorn")}


def latin1_letter(code):
    """Adobe glyph name of an accented Latin-1 letter, from its Unicode name."""
    m = re.fullmatch(
        r"LATIN (CAPITAL|SMALL) LETTER ([A-Z]+)(?: WITH ([A-Z ]+))?",
        unicodedata.name(chr(code)),
    )
    if not m:
        return None
    case, base, mark = m.groups()
    upper = case == "CAPITAL"
    if base in LIGATURE_LETTERS:
        return LIGATURE_LETTERS[base][0 if upper else 1]
    if base == "O" and mark == "STROKE":
        return "Oslash" if upper else "oslash"
    name = base if upper else base.lower()
    if mark:
        name += ACCENTS[mark]  # KeyError on an unmapped accent is intended
    return name


def winansi_glyph_names():
    """code -> Adobe glyph name for WinAnsi 32..=126 and 160..=255."""
    names = dict(PUNCTUATION)
    for i, digit in enumerate(DIGITS):
        names[48 + i] = digit
    for c in range(65, 91):
        names[c] = chr(c)
    for c in range(97, 123):
        names[c] = chr(c)
    for c in range(160, 256):
        names[c] = LATIN1_SYMBOLS.get(c) or latin1_letter(c)
    missing = [c for c in [*range(32, 127), *range(160, 256)] if not names.get(c)]
    if missing:
        sys.exit(f"no glyph name for codes {missing}")
    return names


def parse_afm(font):
    """(glyph name -> width, descriptor metrics) from core/afm/<font>.afm."""
    text = (AFM_DIR / f"{font}.afm").read_text(encoding="latin-1")
    widths = {name: int(w) for w, name in re.findall(r"^C -?\d+ ; WX (\d+) ; N (\S+) ;", text, re.M)}

    def integer(key):
        m = re.search(rf"^{key} (-?\d+)\s*$", text, re.M)
        if not m:
            sys.exit(f"{font}.afm: {key} is missing or not an integer")
        return int(m.group(1))

    bbox = re.search(r"^FontBBox (-?\d+) (-?\d+) (-?\d+) (-?\d+)\s*$", text, re.M)
    if not bbox:
        sys.exit(f"{font}.afm: FontBBox is missing")
    return widths, {
        "bbox": [int(x) for x in bbox.groups()],
        "ascent": integer("Ascender"),
        "descent": integer("Descender"),
        "cap_height": integer("CapHeight"),
        "italic_angle": integer("ItalicAngle"),
        "stem_v": integer("StdVW"),
    }


def render():
    if not (AFM_DIR / "LICENSE").is_file():
        sys.exit("core/afm/LICENSE is missing; Adobe's terms forbid distributing the AFM files without it")
    names = winansi_glyph_names()
    parts = [HEADER]
    for font in FONTS:
        widths, d = parse_afm(font)
        absent = sorted(c for c, n in names.items() if n not in widths)
        if absent:
            sys.exit(f"{font}.afm has no glyph for codes {[(c, names[c]) for c in absent]}")
        table = [0] * 256
        for code, name in names.items():
            table[code] = widths[name]
        rows = ",\n".join("        " + ", ".join(map(str, table[i:i + 16])) for i in range(0, 256, 16))
        parts.append(
            f"pub static {font.upper().replace('-', '_')}: Metrics = Metrics {{\n"
            f"    widths: [\n{rows},\n    ],\n"
            f"    bbox: {d['bbox']}, ascent: {d['ascent']}, descent: {d['descent']},\n"
            f"    cap_height: {d['cap_height']}, italic_angle: {d['italic_angle']}, stem_v: {d['stem_v']},\n"
            f"}};\n"
        )
    return "\n".join(parts)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 with a diff if out of date")
    args = ap.parse_args()

    new = render()
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if old == new:
            print(f"{OUT.relative_to(ROOT)} is up to date")
            return 0
        sys.stdout.writelines(difflib.unified_diff(
            old.splitlines(keepends=True), new.splitlines(keepends=True),
            fromfile=f"{OUT.relative_to(ROOT)} (on disk)", tofile="regenerated"))
        return 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(new)} bytes)" if old != new else f"{OUT.relative_to(ROOT)} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
